CREATE TABLE IF NOT EXISTS minutes_lines (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(20) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL,
 base_minutes INT UNSIGNED NOT NULL DEFAULT 8,
 base_rate_cents INT UNSIGNED NOT NULL DEFAULT 50,
 direct_rate_cents INT UNSIGNED NULL,
 enabled TINYINT(1) NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS minutes_route_aliases (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 line_id INT UNSIGNED NOT NULL,
 name VARCHAR(255) NOT NULL,
 normalized_name VARCHAR(255) NOT NULL UNIQUE,
 FOREIGN KEY (line_id) REFERENCES minutes_lines(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS minutes_points (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 line_id INT UNSIGNED NOT NULL,
 name VARCHAR(255) NOT NULL,
 normalized_name VARCHAR(255) NOT NULL,
 point_number INT UNSIGNED NOT NULL DEFAULT 0,
 sanction VARCHAR(8) NOT NULL DEFAULT 'inherit',
 rate_cents INT UNSIGNED NULL,
 tolerance_minutes INT UNSIGNED NOT NULL DEFAULT 0,
 enabled TINYINT(1) NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY ux_minutes_point (line_id,normalized_name,point_number),
 FOREIGN KEY (line_id) REFERENCES minutes_lines(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
